#!/usr/bin/env sh
# Regenerate the SDK documentation set (runtime-neutral, offline, stdlib-only).
#
#   docs/reference/{sdk,catalogindex,compatibility,scrobble,sdktest}.md — generated API reference (godoc2md)
#   llms.txt                                  — LLM index (llmstxt.org layout)
#   llms-full.txt                             — full LLM corpus (guide + reference)
#
# Hand-authored prose lives in README.md, docs/plugin-authoring.md,
# docs/registry-admission-runbook.md, and COMPATIBILITY.md; this script never
# touches those. Run after any exported-API or doc-comment change:
# script/gen-docs.sh
set -eu
cd "$(dirname "$0")/.."

MODULE=github.com/beamfall/plugin-sdk
VERSION=$(sed -n 's/^const Version = "\(.*\)"$/\1/p' bundle.go)

mkdir -p docs/reference
go run ./script/godoc2md .          "$MODULE"         > docs/reference/sdk.md
go run ./script/godoc2md ./catalogindex "$MODULE/catalogindex" > docs/reference/catalogindex.md
go run ./script/godoc2md ./compatibility "$MODULE/compatibility" > docs/reference/compatibility.md
go run ./script/godoc2md ./scrobble "$MODULE/scrobble" > docs/reference/scrobble.md
go run ./script/godoc2md ./sdktest  "$MODULE/sdktest"  > docs/reference/sdktest.md

cat > llms.txt <<EOF
# Beamfall Plugin SDK

> \`$MODULE\` (v$VERSION) is the Go contract for Beamfall plugins: the
> declarative Bundle manifest, the seams a plugin implements and Beamfall Core
> consumes, and the sdktest conformance harness that proves a plugin honors them.
> Dependencies: Go standard library plus golang.org/x/text (Unicode
> normalization) only. AGPL-3.0-only.
> Regenerated by script/gen-docs.sh — do not edit by hand.

## Docs

- [Plugin authoring guide](docs/plugin-authoring.md): concepts, seams, and the workflow for building a plugin module
- [Registry admission runbook](docs/registry-admission-runbook.md): mechanical admission gates (sdktest.Admit) vs. the manual legality/malware review
- [README](README.md): overview, package map, quick start, and first-party plugins
- [Compatibility & versioning](COMPATIBILITY.md): pre-1.0 semver policy and release checks

## API reference (generated)

- [package sdk](docs/reference/sdk.md): plugin identity, Bundle declaration, vocabularies, Parser/MatchScorer and importer Source seams
- [package catalogindex](docs/reference/catalogindex.md): offline verification and local filtering for the global signed catalog index
- [package compatibility](docs/reference/compatibility.md): exact producer-owned SDK compatibility evidence for canonical plugin artifacts
- [package scrobble](docs/reference/scrobble.md): neutral scrobble dispatcher engine, Adapter seam, and types
- [package sdktest](docs/reference/sdktest.md): cross-plugin conformance harness — golden parse/score vectors, Bundle invariants, and registry admission
EOF

{
  printf '# Beamfall Plugin SDK — full documentation corpus (v%s)\n' "$VERSION"
  printf '# Generated by script/gen-docs.sh — do not edit by hand.\n\n'
  for f in README.md docs/plugin-authoring.md docs/registry-admission-runbook.md COMPATIBILITY.md \
           docs/reference/sdk.md docs/reference/catalogindex.md docs/reference/compatibility.md \
           docs/reference/scrobble.md docs/reference/sdktest.md; do
    printf '\n---\nsource: %s\n---\n\n' "$f"
    cat "$f"
  done
} > llms-full.txt

echo "gen-docs: wrote docs/reference/{sdk,catalogindex,compatibility,scrobble,sdktest}.md llms.txt llms-full.txt"
